#ifndef BORROW_H
#define BORROW_H

#include "ast.h"

// 借用检查（L1：词法作用域 + 跨函数借用签名）。
//
// 只检查 `&T` / `&mut T` 两种借用类型，`*T` 裸指针一律放行 —— 裸指针是「我自己负责」
// 的出口，检查它就等于禁止写底层代码。
//
// 四条规则，全部是词法作用域的，不做 NLL 那种基于活跃点的分析：
//
//   1. 逃逸：函数不能返回指向本函数栈帧的借用。判断依据是左值路径有没有穿过指针 ——
//      `&local.field` 在栈帧里（拒绝），`&param.field` 在指针后面（放行）。
//   2. 秩：借用的「指向秩」不能大于接收它的变量的作用域秩。赋值把深作用域的借用
//      写进浅作用域的变量时报错。
//   3. 别名：`&mut x` 在它所在作用域结束前独占 x —— 期间不能再借、不能读写 x。
//      共享借用 `&x` 可以并存，但和 `&mut x` 互斥。
//   4. 签名：返回借用的函数必须**恰好有一个引用参数**，返回值就借自它（Rust 省略
//      规则的子集）。调用点据此把借用来源的秩继续传下去，所以
//      `return first(&local)` 同样会被规则 1 拦下。
//
// 规则 3 是**保守**的：`let p = &mut x; p[0] = 1; x = 2;` 里最后一句在 Rust 的 NLL
// 下合法（p 已经不再使用），这里仍然报错。词法版本换来实现简单和可预测 —— 报错位置
// 永远等于 `&mut` 所在的作用域，不会因为后面有没有用到 p 而变。
//
// 诊断走 `report_error_soft`：**报完继续检查**，一个文件里的多处借用错误会一次全报
// （达到 TAP_MAX_ERRORS 条才停）。返回 0 表示通过，1 表示报了错 —— 调用方据此决定
// 是否继续往下生成代码，报过错之后的状态不再可信，不能进 Codegen。
int check_borrows(ProgramNode *program);

#endif
